export type ChipTone = "ok" | "warn" | "crit" | "info" | "mute";

const TONE: Record<ChipTone, string> = {
  ok: "bg-pf-ok-soft text-pf-ok",
  warn: "bg-pf-warn-soft text-pf-warn",
  crit: "bg-pf-crit-soft text-pf-crit",
  info: "bg-pf-info-soft text-pf-info",
  mute: "bg-pf-line-soft text-pf-muted",
};

/** Status chip (product UI only): a dot plus a word. */
export function Chip({ tone, children, className }: { tone: ChipTone; children: React.ReactNode; className?: string }) {
  return (
    <span className={cn("inline-flex h-6 items-center gap-1.5 rounded-full px-2.5 text-xs font-semibold whitespace-nowrap before:size-1.5 before:rounded-full before:bg-current before:content-['']", TONE[tone], className)}>
      {children}
    </span>
  );
}

/** Dashed "Demo" marker on synthetic product data. */
export function DemoTag({ children }: { children: React.ReactNode }) {
  return <span className="rounded border border-dashed border-pf-line px-1.5 py-[3px] text-[11px] leading-none font-medium whitespace-nowrap text-pf-muted">{children}</span>;
}

