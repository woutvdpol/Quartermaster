/*
 * /auctions/<slug>/lot/<n> — the lot page (design "Main", phone: "Phone"): the product's gallery, bid
 * box (live price, reserve, countdown, status, maximum bid, quick bids), bid history. The lot data is
 * live through the auction's stream; the bid box itself is per visitor and never cached.
 */

// Explicit (route types are generated by `next dev/build`, which this change must not depend on).
type Props = { params: Promise<{ slug: string; lotNumber: string }> };

async function load(slug: string, rawNumber: string) {
  const { shop, auction, verdicts } = await loadAuction(slug);
  const n = /^\d{1,6}$/.test(rawNumber) ? Number(rawNumber) : NaN;
  const lotRow = auction.lots.find((l) => l.lotNumber === n);
  if (!lotRow) notFound();
  const lot = await getPublicLot(shop.tenant.id, lotRow.id);
  if (!lot) notFound();
  const source = await getProduct(shop.tenant.id, lot.stockCode);
  const translated = source ? await translateProduct(shop.tenant.id, shop.locale, source) : null;
  return { shop, auction, lot, product: translated?.product ?? null, descriptionTranslated: translated?.descriptionTranslated ?? false, geoBlurred: verdicts[lot.productId]?.blurred ?? false };
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug, lotNumber } = await params;
  const { shop, auction, lot, product, geoBlurred } = await load(slug, lotNumber);
  const t = pickCopy(auctionCopies, shop.locale);
  const title = t.lotPage.metaTitle(lot.lotNumber, product?.title ?? lot.title);
  const description = metaDescription(t.lotPage.metaDescription(product?.title ?? lot.title, auction.title, formatBidMoney(displayPrice(lot), shop.tenant.currency, shop.locale)));
  const alternates = shopAlternates(shop, lotHref(auction.slug, lot.lotNumber));
  const viewer = await loadViewer(shop.tenant.id);
  const locked = Boolean(product?.blurred && shop.settings.legal.blurSensitiveForGuests && viewer.kind === "guest");
  if (locked) return { title, alternates: { canonical: alternates.canonical }, robots: { index: false, follow: false } };
  const image = product && !geoBlurred ? productOgImage(product) : null;
  return {
    title,
    description,
    alternates,
    openGraph: { title, description, url: alternates.canonical, siteName: shop.shopName, ...(image ? { images: [image] } : {}) },
    twitter: { card: "summary_large_image", title, description },
  };
}

export default async function LotPage({ params }: Props) {
  const { slug, lotNumber } = await params;
  const { shop, auction, lot, product, descriptionTranslated, geoBlurred } = await load(slug, lotNumber);
  const tenantId = shop.tenant.id;
  const t = pickCopy(auctionCopies, shop.locale);
  const locale = shop.locale;
  const path = lotHref(auction.slug, lot.lotNumber);
  const viewer = await loadViewer(tenantId);
  const [termsHref, mine, tableRow, seo] = await Promise.all([
    auctionTermsHref(tenantId),
    viewer.kind === "customer" && viewer.verified ? getMyLotState(tenantId, lot.id, viewer.customerId) : Promise.resolve(null),
    db.auction.findFirst({ where: { id: auction.id, tenantId }, select: { incrementTable: true } }),
    loadSeoShop(shop),
  ]);
  const locked = Boolean(product?.blurred && shop.settings.legal.blurSensitiveForGuests && viewer.kind === "guest");
  const here = localizePath(path, locale);
  const bidViewer: BidViewer =
    viewer.kind === "guest"
      ? { kind: "guest", loginHref: loginHref(here), registerHref: `/register?next=${encodeURIComponent(here)}` }
      : viewer.kind === "staff"
        ? { kind: "staff" }
        : !viewer.verified
          ? { kind: "unverified", verifyHref: VERIFY_EMAIL_PATH }
          : { kind: "customer", isLeading: mine?.isLeading ?? false, myMax: mine?.myMax ?? null, bidderNumber: mine?.bidderNumber ?? null, termsAccepted: mine?.termsAccepted ?? false, hasBid: mine?.myMax != null };
  const { legal } = shop.settings;
  const ageConfirm = lot.ageRestricted && legal.ageVerification === "checkout" ? legal.minimumAge : null;
  const renderedAt = Date.parse(auction.serverTime);
  const eyebrow = [t.stockCode(lot.stockCode), product?.categoryPath.at(-1)?.title].filter(Boolean).join(" · ");
  const total = auction.lots.length;
  const { history, auction: _summary, ...publicLot } = lot;
  void _summary;

  // schema.org has no auction type: Product + Offer at the current price, valid until the lot closes.
  const closed = lot.closed;
  const ldStatus: PublicStatus = lot.status === "SOLD" ? "sold" : closed ? "reserved" : "available";
  const jsonLd = product && !locked
    ? (() => {
        const base = productJsonLd(seo.seo, { ...product, href: path, price: displayPrice(lot), images: geoBlurred ? [] : product.images }, ldStatus, { showPrice: true, locale });
        return ldStatus === "available" && base.offers ? { ...base, offers: { ...base.offers, priceValidUntil: lot.closesAt.slice(0, 10) } } : base;
      })()
    : null;

  return (
    <AuctionLiveProvider auctionId={auction.id} initialLots={auction.lots} serverTime={auction.serverTime}>
      {jsonLd ? <JsonLd data={jsonLd} /> : null}
      <Container className="flex flex-col gap-5 pt-5 pb-36 sm:pt-6 lg:pb-12">
        <Breadcrumbs
          items={[{ label: t.index.title, href: AUCTIONS_PATH }, { label: auction.title, href: auctionHref(auction.slug) }, { label: total > 1 ? t.lotOf(lot.lotNumber, total) : t.lot(lot.lotNumber) }]}
          jsonLdBase={shop.origin}
          locale={locale}
        />
        <div className="grid gap-8 lg:grid-cols-[minmax(0,1.2fr)_minmax(0,1fr)] lg:gap-12">
          <div className="flex min-w-0 flex-col gap-8">
            <div className="relative">
              {locked || geoBlurred || !product ? (
                <div className="relative aspect-[4/3] overflow-hidden rounded-shop bg-shop-sunken">
                  <LockedImg blurDataUrl={product?.images[0]?.blurDataUrl ?? null} />
                </div>
              ) : (
                <ProductGallery images={galleryImages(product.images)} title={product.title} />
              )}
              <span className="pointer-events-none absolute top-3 left-3 rounded-shop-control bg-shop-ink px-3 py-1 text-sm font-semibold text-shop-bg">{t.lot(lot.lotNumber)}</span>
            </div>
            {product?.description && !locked ? (
              <section aria-labelledby="lot-desc" className="hidden max-w-3xl lg:block">
                <h2 id="lot-desc" className="mb-4 text-2xl text-shop-ink">
                  {t.lotPage.description}
                </h2>
                <div lang={locale !== "en" && !descriptionTranslated ? "en" : undefined}>
                  <Markdown source={product.description} />
                </div>
              </section>
            ) : null}
          </div>

          <div className="flex min-w-0 flex-col gap-5 lg:sticky lg:top-24 lg:self-start">
            <p className="font-shop-mono text-[0.8rem] text-shop-accent">{eyebrow}</p>
            <h1 className="-mt-2 text-[1.75rem] leading-[1.1] tracking-[-0.03em] text-shop-ink sm:text-[2.25rem]">{product?.title ?? lot.title}</h1>
            <LotBidding
              initialLot={publicLot}
              auction={{ id: auction.id, opensAt: auction.opensAt, extendSeconds: auction.extendSeconds }}
              currency={shop.tenant.currency}
              timeZone={shop.tenant.timezone}
              renderedAt={renderedAt}
              table={tableOrDefault(tableRow?.incrementTable)}
              viewer={bidViewer}
              initialHistory={history}
              termsHref={termsHref}
              productHref={product?.href ?? `/product/${lot.stockCode}`}
              ageConfirm={ageConfirm}
            />
          </div>

          {product?.description && !locked ? (
            <section aria-labelledby="lot-desc-m" className="max-w-3xl lg:hidden">
              <h2 id="lot-desc-m" className="mb-4 text-xl text-shop-ink">
                {t.lotPage.description}
              </h2>
              <div lang={locale !== "en" && !descriptionTranslated ? "en" : undefined}>
                <Markdown source={product.description} />
              </div>
            </section>
          ) : null}
        </div>
      </Container>
    </AuctionLiveProvider>
  );
}
