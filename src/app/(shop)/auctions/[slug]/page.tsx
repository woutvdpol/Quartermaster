/*
 * /auctions/<slug> — one auction's catalogue (design "Catalogue"): header with status, opening/first
 * close and a live clock to the next closing lot; filter chips; the live lot grid. One stream per page
 * (AuctionLiveProvider). Per-visitor data (own bids, wishlist) is read per request, never cached.
 */

// Explicit (route types are generated by `next dev/build`, which this change must not depend on).
type Props = { params: Promise<{ slug: string }> };

const DATE_OPTS: Intl.DateTimeFormatOptions = { weekday: "short", day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const { shop, auction } = await loadAuction(slug);
  const t = pickCopy(auctionCopies, shop.locale);
  const description = metaDescription(auction.description ? markdownToPlainText(auction.description) : null, t.catalogue.metaDescription(auction.title, t.lots(auction.lots.length), shop.shopName));
  const alternates = shopAlternates(shop, auctionHref(auction.slug));
  return {
    title: auction.title,
    description,
    alternates,
    openGraph: { ...shopOgDefaults(shop), url: alternates.canonical, title: auction.title, description },
  };
}

/** An .ics file (data: URL) for the first closing time — "Add to calendar". */
function calendarHref(title: string, start: string, url: string): string {
  const stamp = (iso: string) => iso.replace(/[-:]/g, "").replace(/\.\d{3}/, "");
  const end = new Date(Date.parse(start) + 60 * 60 * 1000).toISOString();
  const esc = (s: string) => s.replace(/[\\;,]/g, (m) => `\\${m}`).replace(/\n/g, "\\n");
  const ics = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Quartermaster//Auctions//EN",
    "BEGIN:VEVENT",
    `UID:${stamp(start)}-${encodeURIComponent(url)}`,
    `DTSTAMP:${stamp(new Date().toISOString())}`,
    `DTSTART:${stamp(start)}`,
    `DTEND:${stamp(end)}`,
    `SUMMARY:${esc(title)}`,
    `URL:${url}`,
    "END:VEVENT",
    "END:VCALENDAR",
  ].join("\r\n");
  return `data:text/calendar;charset=utf-8,${encodeURIComponent(ics)}`;
}

export default async function AuctionCataloguePage({ params }: Props) {
  const { slug } = await params;
  const { shop, auction, verdicts } = await loadAuction(slug);
  const tenantId = shop.tenant.id;
  const t = pickCopy(auctionCopies, shop.locale);
  const viewer = await loadViewer(tenantId);
  const productIds = auction.lots.map((l) => l.productId);
  const [extras, mine, watched] = await Promise.all([
    lotExtras(tenantId, productIds),
    viewer.kind === "customer" ? viewerInAuction(tenantId, auction.id, viewer.customerId) : Promise.resolve(null),
    viewer.kind === "customer" ? watchedProductIds(tenantId, viewer.customerId, productIds) : Promise.resolve([]),
  ]);
  const lockSensitive = shop.settings.legal.blurSensitiveForGuests && viewer.kind === "guest";
  const renderedAt = Date.parse(auction.serverTime);
  const date = (iso: string) => formatShopDate(iso, shop.locale, DATE_OPTS, shop.tenant.timezone);
  const upcoming = auction.status === "PUBLISHED" && Date.parse(auction.opensAt) > renderedAt;
  const closed = auction.status === "CLOSED";
  const eyebrow = closed ? t.catalogue.eyebrowClosed : upcoming ? t.catalogue.eyebrowUpcoming : t.catalogue.eyebrowLive;
  const extendMin = Math.max(1, Math.round(auction.extendSeconds / 60));

  const hrefs: Record<string, string> = {};
  const images: Record<string, LotCardImage> = {};
  const categories: Record<string, { slug: string; title: string } | null> = {};
  for (const l of auction.lots) {
    hrefs[l.id] = lotHref(auction.slug, l.lotNumber);
    images[l.id] = lotCardImage(extras[l.productId], l.title, { lockSensitive, geoBlurred: verdicts[l.productId]?.blurred ?? false });
    categories[l.id] = extras[l.productId]?.category ?? null;
  }
  const watchedSet = new Set(watched);
  const pageUrl = new URL(auctionHref(auction.slug), shop.origin).toString();

  return (
    <AuctionLiveProvider auctionId={auction.id} initialLots={auction.lots} serverTime={auction.serverTime}>
      <JsonLd
        data={collectionPageJsonLd({
          origin: shop.origin,
          path: auctionHref(auction.slug),
          name: auction.title,
          description: auction.description ? markdownToPlainText(auction.description) : null,
          locale: shop.locale,
          total: auction.lots.length,
          items: auction.lots.slice(0, 100).map((l) => ({ href: hrefs[l.id], name: `${t.lot(l.lotNumber)}: ${l.title}` })),
        })}
      />
      <Container className="flex flex-col gap-6 py-6 sm:py-8">
        <Breadcrumbs items={[{ label: t.index.title, href: AUCTIONS_PATH }, { label: auction.title }]} jsonLdBase={shop.origin} locale={shop.locale} />

        <section className="flex flex-wrap items-end justify-between gap-5 rounded-shop bg-shop-sunken px-5 py-6 sm:px-7">
          <div className="flex max-w-2xl flex-col gap-2">
            <span className="font-shop-mono text-xs tracking-[0.12em] text-shop-accent uppercase">{eyebrow}</span>
            <h1 className="text-[2rem] leading-[1.05] tracking-[-0.03em] text-shop-ink sm:text-[2.6rem]">{auction.title}</h1>
            <p className="text-shop-ink-2">
              {closed
                ? t.catalogue.closedOn(date(auction.lots.reduce((m, l) => (l.closesAt > m ? l.closesAt : m), auction.firstCloseAt)))
                : auction.type === "DAY"
                  ? t.catalogue.intro(t.lots(auction.lots.length), date(auction.firstCloseAt), auction.lots.length > 1 ? t.catalogue.gap(auction.gapSeconds) : "", extendMin)
                  : null}
              {upcoming ? <> {t.catalogue.opensOn(date(auction.opensAt))}</> : null}
            </p>
            {auction.description ? (
              <div className="mt-1 text-sm text-shop-ink-2">
                <Markdown source={auction.description} />
              </div>
            ) : null}
          </div>
          <div className="flex flex-col gap-1 text-left sm:text-right">
            <NextClosing opensAt={auction.opensAt} renderedAt={renderedAt} />
            {!closed ? (
              <a href={calendarHref(auction.title, upcoming ? auction.opensAt : auction.firstCloseAt, pageUrl)} download={`${auction.slug}.ics`} className="text-sm text-shop-ink-2 underline underline-offset-4 hover:text-shop-ink">
                {t.catalogue.addToCalendar}
              </a>
            ) : null}
          </div>
        </section>

        <CatalogueView
          initialLots={auction.lots}
          hrefs={hrefs}
          images={images}
          categories={categories}
          viewer={mine ? { bidderNumber: mine.bidderNumber, bidLotIds: mine.bidLotIds, watchedLotIds: auction.lots.filter((l) => watchedSet.has(l.productId)).map((l) => l.id) } : null}
          opensAt={auction.opensAt}
          currency={shop.tenant.currency}
          renderedAt={renderedAt}
        />
      </Container>
    </AuctionLiveProvider>
  );
}
